// Regenerates src/icons.js from Material Symbols (Apache-2.0, @material-symbols/svg-400).
// Run: node tools/gen-icons.mjs
import fs from "node:fs";

const MAP = {
  chart: "bar_chart",
  plus: "add",
  edit: "edit_square",
  send: "arrow_upward",
  chat: "chat",
  search: "search",
  shield: "verified_user",
  review: "fact_check",
  logout: "logout",
  file: "description",
  arrow: "chevron_right",
  back: "arrow_back",
  refresh: "refresh",
  check: "check",
  done: "check_circle",
  users: "group",
  user: "person",
  account: "manage_accounts",
  key: "key",
  password: "lock_reset",
  terminal: "terminal",
  plug: "cable",
  copy: "content_copy",
  x: "close",
  menu: "menu",
  lock: "lock",
  activity: "history",
  monitor: "computer",
  more: "more_horiz",
  trash: "delete",
  info: "info",
  alert: "warning",
  error: "error",
  external: "open_in_new",
  light: "light_mode",
  dark: "dark_mode",
  calculate: "calculate",
  compare: "compare_arrows",
  block: "block",
  expand: "keyboard_arrow_down",
  database: "database",
  help: "help",
};

const out = {};
for (const [name, symbol] of Object.entries(MAP)) {
  const svg = fs.readFileSync(
    `node_modules/@material-symbols/svg-400/outlined/${symbol}.svg`,
    "utf8",
  );
  const d = svg.match(/ d="([^"]+)"/);
  if (!d) throw new Error(`No path in ${symbol}`);
  out[name] = d[1];
}
const body = Object.entries(out)
  .map(([k, v]) => `  ${k}:\n    "${v}",`)
  .join("\n");
fs.writeFileSync(
  "src/icons.js",
  `// Generated by tools/gen-icons.mjs. Paths are Material Symbols (Outlined, weight 400),\n// Copyright Google LLC, Apache License 2.0. View box: 0 -960 960 960.\nexport const ICON_PATHS = {\n${body}\n};\n`,
);
console.log(Object.keys(out).length, "icons");
